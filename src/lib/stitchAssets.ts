export const getEquipmentImage = (code: string = '', type: string = '') => {
  const c = (code || '').toUpperCase();
  const t = (type || '').toUpperCase();

  if (c.includes('KOM') || c.includes('PC200') || c.includes('EXCA') || t.includes('EXCAVATOR')) {
    return STITCH_IMAGES.EXCAVATOR;
  }
  if (c.includes('BULL') || c.includes('CAT') || c.includes('D85') || c.includes('D6') || t.includes('BULLDOZER')) {
    return STITCH_IMAGES.BULLDOZER;
  }
  if (c.includes('VIBR') || c.includes('SAK') || c.includes('SV520') || c.includes('SD110') || c.includes('ROLL') || t.includes('ROLLER')) {
    return STITCH_IMAGES.ROLLER;
  }
  if (c.includes('LOAD') || c.includes('WA380') || t.includes('LOADER')) {
    return STITCH_IMAGES.LOADER;
  }
  if (c.includes('CRAN') || c.includes('TAD') || c.includes('GR700') || t.includes('CRANE')) {
    return STITCH_IMAGES.CRANE;
  }
  return STITCH_IMAGES.EXCAVATOR;
};

export const getUserAvatar = (roleName?: string) => {
  if (roleName === 'ADMIN') return STITCH_IMAGES.ADMIN_AVATAR;
  if (roleName === 'STAFF') return STITCH_IMAGES.STAFF_AVATAR;
  return STITCH_IMAGES.CUSTOMER_AVATAR;
};
