/** Substitusikan placeholder `{nama}` dengan nilai params. */
function isiTemplate(str: string, params?: ParamsI18n): string {
	if (!params) return str;
	return str.replace(/\{(\w+)\}/g, (asli, kunci: string) =>
		kunci in params ? String(params[kunci]) : asli,
	);
}

